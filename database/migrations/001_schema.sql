-- OpenCode Free Relay — PostgreSQL schema
-- Requires PostgreSQL 14+ (identity columns, jsonb, inet/cidr).

CREATE OR REPLACE FUNCTION relay_set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS plans (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                text NOT NULL UNIQUE,
    name                text NOT NULL,
    description         text NOT NULL DEFAULT '',
    price_credits       numeric(20,6) NOT NULL DEFAULT 0 CHECK (price_credits >= 0),
    daily_requests      integer NOT NULL DEFAULT 200,       -- -1 = unlimited
    daily_tokens        bigint  NOT NULL DEFAULT 5000000,    -- -1 = unlimited
    rpm                 integer NOT NULL DEFAULT 30,         -- requests/minute, 0 = blocked
    concurrency         integer NOT NULL DEFAULT 3,
    allowed_models      text[] NULL,                         -- NULL = all enabled models
    discount_multiplier numeric(8,4) NOT NULL DEFAULT 1 CHECK (discount_multiplier > 0),
    is_default          boolean NOT NULL DEFAULT false,
    active              boolean NOT NULL DEFAULT true,
    sort_order          integer NOT NULL DEFAULT 0,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS plans_one_default_idx
    ON plans ((is_default)) WHERE is_default;

CREATE TABLE IF NOT EXISTS users (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            text NOT NULL,
    email               text NULL,
    password_hash       text NOT NULL,
    role                text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    status              text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'pending', 'suspended')),
    plan_id             bigint NULL REFERENCES plans(id) ON DELETE SET NULL,
    balance             numeric(20,6) NOT NULL DEFAULT 0,
    total_requests      bigint NOT NULL DEFAULT 0,
    total_input_tokens  bigint NOT NULL DEFAULT 0,
    total_output_tokens bigint NOT NULL DEFAULT 0,
    total_credits_used  numeric(20,6) NOT NULL DEFAULT 0,
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb,
    last_login_at       timestamptz NULL,
    last_ip             inet NULL,
    invited_by          bigint NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_idx ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx ON users (lower(email)) WHERE email IS NOT NULL;
CREATE INDEX IF NOT EXISTS users_status_idx ON users (status);
CREATE INDEX IF NOT EXISTS users_plan_idx ON users (plan_id);

CREATE TABLE IF NOT EXISTS api_keys (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name            text NOT NULL DEFAULT 'default',
    prefix          text NOT NULL,
    key_hash        text NOT NULL UNIQUE,
    status          text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
    last_used_at    timestamptz NULL,
    expires_at      timestamptz NULL,
    request_count   bigint NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    revoked_at      timestamptz NULL
);
CREATE INDEX IF NOT EXISTS api_keys_user_idx ON api_keys (user_id);
CREATE INDEX IF NOT EXISTS api_keys_hash_idx ON api_keys (key_hash);

CREATE TABLE IF NOT EXISTS invite_codes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash       text NOT NULL UNIQUE,
    label           text NOT NULL DEFAULT '',
    plan_id         bigint NULL REFERENCES plans(id) ON DELETE SET NULL,
    created_by      bigint NULL REFERENCES users(id) ON DELETE SET NULL,
    max_uses        integer NOT NULL DEFAULT 1,
    used_count      integer NOT NULL DEFAULT 0,
    initial_credits numeric(20,6) NOT NULL DEFAULT 0,
    expires_at      timestamptz NULL,
    active          boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS redemption_codes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash   text NOT NULL UNIQUE,
    credits     numeric(20,6) NOT NULL CHECK (credits > 0),
    max_uses    integer NOT NULL DEFAULT 1,
    used_count  integer NOT NULL DEFAULT 0,
    expires_at  timestamptz NULL,
    active      boolean NOT NULL DEFAULT true,
    note        text NOT NULL DEFAULT '',
    created_by  bigint NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS redemption_uses (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_id     bigint NOT NULL REFERENCES redemption_codes(id) ON DELETE CASCADE,
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    credits     numeric(20,6) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (code_id, user_id)
);

CREATE TABLE IF NOT EXISTS credit_transactions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    amount          numeric(20,6) NOT NULL,
    balance_after   numeric(20,6) NOT NULL,
    kind            text NOT NULL,
    reference       text NULL,
    note            text NOT NULL DEFAULT '',
    created_by      bigint NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS credit_transactions_user_idx ON credit_transactions (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS usage_daily (
    user_id             bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day                 date NOT NULL,
    requests            bigint NOT NULL DEFAULT 0,
    input_tokens        bigint NOT NULL DEFAULT 0,
    output_tokens       bigint NOT NULL DEFAULT 0,
    credits             numeric(20,6) NOT NULL DEFAULT 0,
    reserved_requests   integer NOT NULL DEFAULT 0,
    updated_at          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, day),
    CHECK (reserved_requests >= 0)
);
CREATE INDEX IF NOT EXISTS usage_daily_day_idx ON usage_daily (day);

CREATE TABLE IF NOT EXISTS active_requests (
    request_id  uuid PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    api_key_id  bigint NULL REFERENCES api_keys(id) ON DELETE SET NULL,
    endpoint    text NOT NULL DEFAULT '',
    started_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS active_requests_user_idx ON active_requests (user_id);
CREATE INDEX IF NOT EXISTS active_requests_expiry_idx ON active_requests (expires_at);

CREATE TABLE IF NOT EXISTS rate_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    api_key_id  bigint NULL REFERENCES api_keys(id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rate_events_user_time_idx ON rate_events (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS ip_pools (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text NOT NULL UNIQUE,
    cidr                cidr NOT NULL UNIQUE,
    enabled             boolean NOT NULL DEFAULT true,
    weight              integer NOT NULL DEFAULT 100 CHECK (weight > 0),
    lease_ttl_seconds   integer NOT NULL DEFAULT 604800 CHECK (lease_ttl_seconds >= 0),
    interface_name      text NULL,
    status              text NOT NULL DEFAULT 'unknown' CHECK (status IN ('unknown', 'healthy', 'degraded')),
    last_error          text NULL,
    last_checked_at     timestamptz NULL,
    notes               text NOT NULL DEFAULT '',
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ip_pools_ipv6_only CHECK (family(cidr::inet) = 6),
    CONSTRAINT ip_pools_prefix_range CHECK (masklen(cidr::inet) BETWEEN 1 AND 128)
);
CREATE INDEX IF NOT EXISTS ip_pools_enabled_idx ON ip_pools (enabled);

CREATE TABLE IF NOT EXISTS ip_leases (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id         bigint NOT NULL REFERENCES ip_pools(id) ON DELETE CASCADE,
    address         inet NOT NULL UNIQUE,
    request_id      uuid NULL,
    failure_count   integer NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    expires_at      timestamptz NOT NULL,
    released_at     timestamptz NULL,
    CONSTRAINT ip_leases_ipv6_only CHECK (family(address) = 6)
);
CREATE INDEX IF NOT EXISTS ip_leases_pool_idx ON ip_leases (pool_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ip_leases_expiry_idx ON ip_leases (expires_at);

