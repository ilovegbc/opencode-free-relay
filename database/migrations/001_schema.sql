-- A convenience view used by the public status page and admin dashboard.
CREATE OR REPLACE VIEW relay_pool_stats AS
SELECT
    p.id,
    p.name,
    p.cidr::text AS cidr,
    p.enabled,
    p.status,
    p.weight,
    p.lease_ttl_seconds,
    p.last_checked_at,
    p.last_error,
    count(l.id) FILTER (WHERE l.expires_at > now() AND l.released_at IS NULL) AS active_leases,
    max(l.created_at) AS last_lease_at
FROM ip_pools p
LEFT JOIN ip_leases l ON l.pool_id = p.id
GROUP BY p.id;
