    credit_multiplier       numeric(8,4) NOT NULL DEFAULT 1 CHECK (credit_multiplier > 0),
    capabilities            jsonb NOT NULL DEFAULT '{}'::jsonb,
    modalities              jsonb NOT NULL DEFAULT '{}'::jsonb,
    api                     jsonb NOT NULL DEFAULT '{}'::jsonb,
    raw                     jsonb NOT NULL DEFAULT '{}'::jsonb,
    sort_order              integer NOT NULL DEFAULT 0,
    first_seen_at           timestamptz NOT NULL DEFAULT now(),
    last_seen_at            timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS model_catalog_free_idx ON model_catalog (is_free, enabled, available);
CREATE INDEX IF NOT EXISTS model_catalog_last_seen_idx ON model_catalog (last_seen_at DESC);

CREATE TABLE IF NOT EXISTS model_aliases (
    alias       text PRIMARY KEY,
    model_id    text NOT NULL REFERENCES model_catalog(id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now()
